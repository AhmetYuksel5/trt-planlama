export type Anahtar = keyof typeof M;

/* --- Seçili dil --- */

const SAKLA = "trt-planlama-dil";

const dilOku = (): Dil => {
  try {
    const k = localStorage.getItem(SAKLA);
    return DILLER.includes(k as Dil) ? (k as Dil) : "tr";
  } catch {
    return "tr";
  }
};

let dil: Dil = dilOku();

const dinleyiciler = new Set<() => void>();

const uygula = () => {
  document.documentElement.lang = dil;
  // Arapça sağdan sola; tarayıcı yerleşimi mantıksal CSS sayesinde kendisi çeviriyor.
  document.documentElement.dir = dil === "ar" ? "rtl" : "ltr";
  document.title = M.uygulama[dil];
};
uygula();

/* Dil üst pencerede seçiliyor; workspace bölmeleri ve öbür sekmeler yeniden yüklenmeden ona dönsün. */
window.addEventListener("storage", (e) => {
  if (e.key !== SAKLA && e.key !== null) return;
  const yeni = dilOku();
  if (yeni === dil) return;
  dil = yeni;
  uygula();
  dinleyiciler.forEach((d) => d());
});

export const dilAyarla = (yeni: Dil) => {
  dil = yeni;
  try {
    localStorage.setItem(SAKLA, yeni);
  } catch {
    /* özel pencerede saklanamaz, sorun değil */
  }
  uygula();
  dinleyiciler.forEach((d) => d());
};

type Degisken = Record<string, string | number>;

/** Anahtarın verilen dildeki metni; {ad} gibi yer tutucular doldurulur. */
export const metin = (k: Anahtar, d: Dil = dil, p?: Degisken): string => {
  const ham = M[k][d];
  return p ? ham.replace(/\{(\w+)\}/g, (_, x: string) => (x in p ? String(p[x]) : `{${x}}`)) : ham;
};

/** Düz metinse olduğu gibi, üç dilliyse seçili dil. */
export const yaz = (x: Yazi | undefined, d: Dil = dil): string => (x === undefined ? "" : typeof x === "string" ? x : x[d] || x.tr);

export function useDil() {
  const simdiki = useSyncExternalStore(
    (d) => {
      dinleyiciler.add(d);
      return () => dinleyiciler.delete(d);
    },
    () => dil,
  );
  return {
    dil: simdiki,
    t: (k: Anahtar, p?: Degisken) => metin(k, simdiki, p),
    ad: (k: { ad: Yazi } | undefined) => (k ? yaz(k.ad, simdiki) : ""),
  };
}

/* --- Tarih ve saat: Intl ile, Arapçada Latin rakam --- */

const YEREL: Record<Dil, string> = { tr: "tr-TR", ar: "ar-u-nu-latn", en: "en-GB" };

const gunTarihi = (iso: string) => new Date(iso.length === 10 ? iso + "T12:00:00" : iso);

const BICIM: Record<"kisa" | "uzun" | "ay" | "tam", Intl.DateTimeFormatOptions> = {
  kisa: { day: "numeric", month: "short" },
  uzun: { day: "numeric", month: "long", year: "numeric" },
  ay: { month: "long", year: "numeric" },
  tam: { weekday: "long", day: "numeric", month: "long", year: "numeric" },
};

/** "2026-10-02" → "2 Eki" / "2 أكتوبر" / "2 Oct" ya da uzun biçimler. */
export const tarihYaz = (iso: string, d: Dil = dil, bicim: keyof typeof BICIM = "kisa") =>
  new Intl.DateTimeFormat(YEREL[d], BICIM[bicim]).format(gunTarihi(iso));

export const gunAdi = (iso: string, d: Dil = dil) => new Intl.DateTimeFormat(YEREL[d], { weekday: "long" }).format(gunTarihi(iso));

/** Takvim başlıkları: "Ekim", "Eki" ya da "Ekim 2026". */
export const ayAdi = (iso: string, d: Dil = dil, bicim: "uzun" | "kisa" | "yil" = "uzun") =>
  new Intl.DateTimeFormat(YEREL[d], bicim === "yil" ? { month: "long", year: "numeric" } : { month: bicim === "kisa" ? "short" : "long" }).format(gunTarihi(iso));

/** Takvim sütun başı: "Cmt", "السبت", "Sat". */
export const kisaGunAdi = (iso: string, d: Dil = dil) => new Intl.DateTimeFormat(YEREL[d], { weekday: "short" }).format(gunTarihi(iso));

export const saatYaz = (isoZaman: string, d: Dil = dil) =>
  new Intl.DateTimeFormat(YEREL[d], { hour: "2-digit", minute: "2-digit", hour12: false }).format(new Date(isoZaman));

/** Kurumun çıktısındaki gibi: "الجمعة 02 أكتوبر" (gün adı, iki haneli gün, ay). */
export const ciktiTarihi = (iso: string, d: Dil = dil) => {
  const t = gunTarihi(iso);
  const ay = new Intl.DateTimeFormat(YEREL[d], { month: "long" }).format(t);
  return `${gunAdi(iso, d)} ${String(t.getDate()).padStart(2, "0")} ${ay}`;
};

/** Haftalık çıktıdaki gün satırı: "03 أكتوبر السبت" (gün, ay, gün adı). */
export const ciktiGunu = (iso: string, d: Dil = dil) => {
  const t = gunTarihi(iso);
  const ay = new Intl.DateTimeFormat(YEREL[d], { month: "long" }).format(t);
  return `${String(t.getDate()).padStart(2, "0")} ${ay} ${gunAdi(iso, d)}`;
};

/**
 * Hafta aralığı kurumun yazımıyla: aynı ayda "03 - 09 أكتوبر", ay
 * değişiyorsa "31 أكتوبر - 06 نوفمبر".
 */
export const aralikYaz = (bas: string, bit: string, d: Dil = dil) => {
  const ay = (iso: string) => new Intl.DateTimeFormat(YEREL[d], { month: "long" }).format(gunTarihi(iso));
  const g = (iso: string) => String(gunTarihi(iso).getDate()).padStart(2, "0");
  return ay(bas) === ay(bit) ? `${g(bas)} - ${g(bit)} ${ay(bit)}` : `${g(bas)} ${ay(bas)} - ${g(bit)} ${ay(bit)}`;
};

/** "12 dk önce" gibi göreli zaman. */
export const gecenSure = (isoZaman: string, d: Dil = dil) => {
  const fark = (new Date(isoZaman).getTime() - Date.now()) / 1000;
  const rtf = new Intl.RelativeTimeFormat(YEREL[d], { numeric: "auto", style: "short" });
  const mutlak = Math.abs(fark);
  if (mutlak < 60) return rtf.format(Math.round(fark), "second");
  if (mutlak < 3600) return rtf.format(Math.round(fark / 60), "minute");
  if (mutlak < 86400) return rtf.format(Math.round(fark / 3600), "hour");
  return rtf.format(Math.round(fark / 86400), "day");
};
