// Newsdesk kapalıyken Next Day'de "Devral" yok (düğme ve eylem), açılınca var; İş akışları sayfasında durum satırı
const { chromium } = require(process.env.PW);
const B = "http://localhost:4173/";
let gec = 0, kal = 0;
const ok = (k, m) => (k ? (gec++, console.log("✓ " + m)) : (kal++, console.log("✗ " + m)));
(async () => {
  const b = await chromium.launch({ executablePath: process.env.CHROME || undefined });
  const p = await b.newPage({ viewport: { width: 1440, height: 1000 } });
  const hatalar = [];
  p.on("pageerror", (e) => hatalar.push(String(e)));
  p.on("dialog", (x) => x.accept());
  const git = async (h) => { await p.goto("about:blank"); await p.goto(B + h); await p.waitForTimeout(500); };
  const veri = () => p.evaluate(() => JSON.parse(localStorage.getItem("trt-planlama-v23")));
  const yaz = (d) => p.evaluate((x) => { localStorage.setItem("trt-planlama-v23", JSON.stringify(x)); localStorage.setItem("trt-planlama-v23-iz", String(Date.now())); }, d);
  await p.goto(B);
  await p.evaluate(() => { localStorage.clear(); localStorage.setItem("trt-planlama-oturum", "yo3"); localStorage.setItem("trt-planlama-dil", "tr"); });
  await git("#/");
  let d = await veri();
  const plan = d.planlar.filter((x) => x.durum !== "devralindi").sort((a, c) => c.tarih.localeCompare(a.tarih))[0];
  plan.durum = "onayli";
  delete d.newsdeskDevrede;
  await yaz(d);
  const dugme = () => p.locator("button", { hasText: "Planı Newsdesk olarak devral" }).count();
  await p.evaluate(() => localStorage.setItem("trt-planlama-oturum", "nd1"));
  await git("#/nextday/" + plan.id);
  ok((await dugme()) === 0, "Newsdesk kapalıyken onaylı planda Devral düğmesi yok");
  await p.evaluate(() => localStorage.setItem("trt-planlama-oturum", "yo3"));
  await git("#/organizasyon/akislar");
  ok((await p.locator("[data-akis-newsdesk-kapali]").count()) === 1, "İş akışlarında 'Newsdesk sistemde değil' satırı");
  d = await veri();
  d.newsdeskDevrede = true;
  await yaz(d);
  // Devir yetkisi varsayılan kuralda Newsdesk'te: kapalıyken de ona düğme çıkmamalıydı.
  await p.evaluate(() => localStorage.setItem("trt-planlama-oturum", "nd1"));
  await git("#/nextday/" + plan.id);
  ok((await dugme()) === 1, "Newsdesk açıkken Devral düğmesi var");
  await p.evaluate(() => localStorage.setItem("trt-planlama-oturum", "yo3"));
  await git("#/organizasyon/akislar");
  ok((await p.locator("[data-akis-newsdesk-kapali]").count()) === 0, "Newsdesk açıkken satır yok");
  ok(!hatalar.length, "sayfa hatası yok " + hatalar.join(" | "));
  console.log(`\n${gec} geçti, ${kal} kaldı`);
  await b.close();
  process.exit(kal ? 1 : 0);
})();
